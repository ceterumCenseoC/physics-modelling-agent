def generate_hamiltonian_pxp(L):
    """
    Generates the sparse Hamiltonian matrix for the PXP model for a chain of length L.
    The basis states are constrained by the Rydberg blockade (no adjacent 1s).
    
    Args:
        L (int): System size.
        
    Returns:
        H (scipy.sparse.csr_matrix): The Hamiltonian matrix.
        basis (list of int): The list of basis states (integers representing bit strings).
        N (int): Dimension of the Hilbert space.
    """
    # 1. Generate all basis states satisfying the Rydberg blockade constraint
    # A state is an integer from 0 to 2^L - 1.
    # Valid if no two adjacent bits are 1. This means (state & (state << 1)) == 0.
    basis = []
    for s in range(2**L):
        if (s & (s << 1)) == 0:
            basis.append(s)
            
    N = len(basis)
    index_map = {s: i for i, s in enumerate(basis)}
    
    # 2. Construct Hamiltonian using P_{i-1} X_i P_{i+1}
    # H acts symmetrically. We build coordinate lists (row, col, data) for the sparse matrix.
    rows = []
    cols = []
    data = []
    
    # Projector P is |0><0| acting on site i. 
    # Checking if neighbors are 0 is equivalent to checking if they are in ground state.
    # X_i flips the spin at site i.
    # Action: If site i is flipped, new state is s' = s ^ (1 << i).
    # Term exists iff:
    # a) Left neighbor (i-1) is 0 in the original state s.
    # b) Right neighbor (i+1) is 0 in the original state s.
    # c) The resulting state s' must also satisfy the blockade constraint.
    #    (Explicitly checking blockade in s' covers the self-interaction condition for P_i implicitly,
    #    but the condition in H is P_{i-1} X_i P_{i+1}. 
    #    Actually, P_{i-1} X_i P_{i+1} |s>:
    #    - If neighbors in |s> are not 0 -> term is 0.
    #    - If neighbors in |s> are 0 -> apply X. Resulting state might violate blockade?
    #      The Hamiltonian constraint usually ensures valid transitions. 
    #      However, if P_{i-1} and P_{i+1} allow the flip, X_i acts.
    #      Since P projects onto physical subspace of that site, we are in the physical space.
    #      Wait, P_i is projector onto |0>. 
    #      Condition: s has 0 at i-1 and i+1.
    #      Action: Flip s at i.
    #      Does the result s' need to be checked? 
    #      If s has ...0 0 0..., flip middle -> ...0 1 0... (Valid).
    #      If s has ...0 1 0..., flip middle -> ...0 0 0... (Valid).
    #      If s has ...0 0 1..., flip middle -> ...0 1 1... (Invalid! But neighbor check P_{i+1} would fail because i+1 is 1).
    #      Check: P_{i+1} |1> = 0. So terms where neighbor is 1 are killed immediately.
    #      So we only flip s at i if s has neighbors 0.
    
    for idx, state in enumerate(basis):
        for i in range(L):
            # Check neighbors (Periodic Boundary Conditions)
            left = (i - 1) % L
            right = (i + 1) % L
            
            if (state >> left) & 1 == 0 and (state >> right) & 1 == 0:
                # Flip spin at i
                new_state = state ^ (1 << i)
                
                # new_state is guaranteed to be in the basis?
                # If state was ...0 s_i 0..., and both 0s are in P.
                # If s_i was 0, becomes 1. neighbors are 0. Valid.
                # If s_i was 1, becomes 0. Valid.
                # So new_state is in basis.
                
                jdx = index_map[new_state]
                
                rows.append(idx)
                cols.append(jdx)
                data.append(1.0) # Matrix element is 1.0
                
    H = sp.coo_matrix((data, (rows, cols)), shape=(N, N), dtype=np.float64)
    return H.tocsr(), basis, N

def get_translation_reflection_sector(L, basis, k_target=0, p_target=1):
    """
    Block diagonalizes the Hamiltonian into specific symmetry sectors.
    We modify the basis to representation that respects symmetries or simply project.
    Given L=26 is somewhat large, listing states is feasible. 
    However, mapping the full basis to symmetry sectors is better done by 
    identifying the basis states belonging to the sector.
    
    translation operator T: shifts bits right by 1: (s >> 1) + ((s & 1) << (L-1))
    reflection operator P: reverses bits: sum(s_i << (L-1-i))
    
    We need to find basis states that have definite momentum k=0 and parity p=+1.
    This often involves forming linear combinations (symmetrized states).
    
    Approach:
    1. Identify orbits of the symmetry group generated by T and P.
    2. Construct projection operators onto the desired sector.
    3. Build a list of basis vectors (in the full basis space) that form an orthonormal set for the subspace.
    
    Note: Since L=26, the Did0+ sector corresponds to T^2=TR=1. 
    k=0 => T|psi> = +|psi>.
    p=+1 => P|psi> = +|psi>.
    """
    
    # Helper functions for applying symmetries
    def translate(state):
        # Right shift (or left shift, convention choice. Let's use right shift i -> i+1)
        # site 0 goes to 1. usually (x >> 1) | ((x & 1) << (L-1))
        # Let's match simple bit shift: 1010 -> 0101 (Left shift) or 0101 (Right shift?)
        # PXP is symmetric. Let's stick to standard binary dir shift.
        # Right shift: 1010 (10) -> 0101 (5).
        return ((state >> 1) | ((state & 1) << (L - 1))) & ((1 << L) - 1)

    def reflect(state):
        # Mirror bits: 0 <-> L-1
        r = 0
        for i in range(L):
            if (state >> i) & 1:
                r |= 1 << (L - 1 - i)
        return r

    # Helper to count partition (density)
    def count_ones(state):
        return bin(state).count("1")

    # We construct the sector basis manually.
    # We will iterate through the full basis. For each unprocessed state, we generate its orbit.
    # Inside the orbit, we apply projection operators to build states in the required sector.
    
    processed = set()
    sector_basis_indices = [] # Indices of the vectors in the Did0+ subspace
    
    # We need to handle the construction of vectors carefully to avoid numerical issues and redundancy.
    # Dimension of Did0+ for L=26 is approx sqrt(d_total) ~ 4000-5000.
    
    # We will build a list of vectors (sparse or dense list of tuples).
    # Structure: list of tuples (index_in_original_basis, amplitude)
    # However, standard dot products require matrix multiplication. 
    # We'll construct a rectangular matrix Proj (N_sect x N_full).
    # H_sect = Proj @ H_full @ Proj.T
    
    vectors = [] 
    
    # We want to iterate efficiently. 
    # Let's sort basis by density (number of 1s) to make finding Z2 state easier? 
    # Z2 is 13 ones. 
    # Just iterate basis list directly.

    n_states = len(basis)
    state_to_idx = {s: i for i, s in enumerate(basis)}
    
    for i, s in enumerate(basis):
        if s in processed:
            continue
            
        # Generate orbit under T
        orbit_T = []
        current = s
        while current not in orbit_T:
            orbit_T.append(current)
            current = translate(current)
            
        # Check momentum sectors available in this orbit
        # Size of T-orbit
        L_T = len(orbit_T)
        
        # For k=0, we require T eigenvalue +1.
        # We can form the linear combination sum_{x in orbit_T} x.
        # But we also need reflection parity p=+1.
        
        # Because p and T commute or anti-commute depending on definitions?
        # P T P = T^{-1}. [P, T] != 0 generally unless k=0 or pi.
        # For k=0, T|psi> = |psi>. Then P T |psi> = P|psi>. Also T P |psi> = |psi>?
        # If T|psi>=|psi>, then P|psi> has eigenvalue 1 under T? Yes.
        # So we can simultaneously diagonalize for k=0.
        
        # Let's look for states with k=0.
        # State candidates in this T-orbit orbit_T are:
        # |alpha_k> = 1/sqrt(L_T) * sum_{j=0}^{L_T-1} omega^{-kj} T^j |s0>
        # Here s0 is the representative.
        # We only care about k=0.
        # Vector v_T0 (unnormalized): sum_{x in orbit_T} x.
        
        # Now we need to check reflection.
        # Reflect the orbit.
        reflected_orbit = set(reflect(x) for x in orbit_T)
        
        # If reflected_orbit == orbit_T (set equality), the T-orbit is closed under reflection.
        # If not, we need to merge this orbit with its partner? 
        # Actually, for k=0, we can simply symmetrize the sum.
        
        # Let's refine the orbit finding. We should find orbits under the group generated by T and P.
        # But checking eigenvalues is easier.
        
        # Step 1: Find connected component under T and P.
        # Step 2: Decompose this component into irreps.
        
        # For L=26 and k=0, we need to look at the symmetries.
        # Condition: T psi = psi, P psi = psi.
        
        # Construct the combined orbit
        orbit_combined = set()
        stack = [s]
        while stack:
            curr = stack.pop()
            if curr in orbit_combined:
                continue
            orbit_combined.add(curr)
            
            t_curr = translate(curr)
            if t_curr not in orbit_combined: stack.append(t_curr)
            
            p_curr = reflect(curr)
            if p_curr not in orbit_combined: stack.append(p_curr)
            
        # Mark all in orbit_combined as processed
        for st in orbit_combined:
            processed.add(st)
            
        # Now we have a set of states 'orbit_combined'. 
        # We need to find orthonormal vectors with k=0, p=+1 in this span.
        
        # Strategy:
        # 1. Construct projector onto k=0 within this set.
        #    P_k0 = 1/|Group_T| * sum_{g in Group_T} g
        # 2. Apply P_k0 to a generic vector in the set? 
        #    Or better, since we need p=+1 too, we just construct:
        #    |v> = sum_{x in orbit_combined} x ?
        #    No, T-orbit size might be L (26) or divisor.
        #    If orbit size is 26 (full cycle), k runs 0, 2pi/26...
        #    If orbit size is d (d divides 26).
        
        # Let's group by T-orbits inside the combined orbit.
        t_orbits = []
        temp_processed_T = set()
        
        for st in orbit_combined:
            if st in temp_processed_T: continue
            # generate T-orbit
            tc = translate(st)
            curr_t_orb = []
            curr = st
            while curr not in curr_t_orb:
                curr_t_orb.append(curr)
                curr = translate(curr)
            t_orbits.append(curr_t_orb)
            for x in curr_t_orb: temp_processed_T.add(x)
            
        # We have a set of T-orbits. Reflection P maps one T-orbit to another (or itself).
        # P(T(x)) = T^{-1}(P(x)). 
        # If we have a T-orbit with k-content, P maps k to -k.
        # Since we want k=0, we are looking for T-orbits that are invariant under P (contain both k and -k, or k=0).
        # Specifically, for k=0 subspace, we look at the symmetric sum of T-orbits.
        
        # For each pair of T-orbits (O, P(O)):
        # If O != P(O): combination O + P(O) has p-up. O - P(O) has p-down.
        # And they maintain T-properties? 
        # Sum(O) and Sum(P(O)) both have k=0.
        # So v = sum(O) + sum(P(O)) has k=0, p=+1.
        
        # If O == P(O): The T-orbit is symmetric.
        # Sum(O) has k=0, p=+1.
        # (Potentially other vectors with different k).
        
        # So the algorithm:
        # 1. Iterate over t_orbits.
        # 2. Check if reflected.
        # 3. If not reflected yet, take representative.
        #    If P(O) == O:
        #        v = sum of states in O.
        #    Else:
        #        Find partner O_p.
        #        v = sum of states in O + sum of states in O_p.
        #    Normalize v. 
        #    Is v orthogonal to others? Yes, disjoint support if T-orbits are disjoint.
        
        visited_pairs = set()
        
        for orb in t_orbits:
            # Check if processed
            # We can identify T-orbits by a tuple of ints, but simpler: check first element
            rep = orb[0]
            if rep in visited_pairs: continue
            
            reflected_rep = reflect(rep)
            
            # Find the t_orbit containing reflected_rep
            orb_p = None
            for candidate in t_orbits:
                if reflected_rep in candidate:
                    orb_p = candidate
                    break
            
            if orb_p is None: raise ValueError("Partner orbit not found")
            
            # Check if symmetric
            is_symmetric = (set(orb) == set(orb_p))
            
            if is_symmetric:
                # Only one vector needed from this specific orbit structure for k=0, p=+1
                # unless the orbit has divisors where other k=0 vectors exist?
                # No, within a single T-orbit, the k=0 vector is unique (Sum).
                # If orbit size is not L, but still symmetric, Sum is unique.
                
                # Construct vector
                # v = sum_{x in orb} |x>
                # Normalization: sqrt(len(orb))
                
                components = [(state_to_idx[x], 1.0) for x in orb]
                norm = math.sqrt(len(orb))
                
                # Normalize
                components = [(idx, val/norm) for idx, val in components]
                vectors.append(components)
                
                # Mark all in orb as processed
                for x in orb:
                    visited_pairs.add(x)
                    # Note: we don't mark orb_p because orb_p is orb
                    
            else:
                # Asymmetric pair O, O_p
                # Construct v = sum(O) + sum(O_p)
                # Norm squared = len(O) + len(O_p) (since disjoint and real positive)
                # Wait, does O and O_p have same size? T-orbits invariant under translation.
                # Yes, P maps T-orbit to T-orbit preserving structure.
                
                components = []
                for x in orb:
                    components.append((state_to_idx[x], 1.0))
                for x in orb_p:
                    components.append((state_to_idx[x], 1.0))
                    
                norm = math.sqrt(len(orb) + len(orb_p))
                components = [(idx, val/norm) for idx, val in components]
                vectors.append(components)
                
                # Mark both as processed
                for x in orb: visited_pairs.add(x)
                for x in orb_p: visited_pairs.add(x)

    # Sort sector basis vectors? 
    # For reproducibility, maybe by largest component index or value?
    # Not strictly necessary but good for debugging.
    # Let's extract the Z2 state index first to use later.
    # |Z2> = 101010...
    # 26 sites. 13 ones.
    # Pattern 1010... starting with 1.
    s_z2 = 0
    for i in range(L):
        if i % 2 == 0: # Site 0 is 1 (LSB or MSB? Let's assume bit 0 is site 1 = 1)
            # If bit 0 is leftmost. 
            # In translate((s>>1)|...), bit 0 moves to 1. So bit 0 is 'left' or 'site 1'.
            # Let's assume standard integer binary: 1 is ...0001.
            # If state 1 represents |...001>. Site 0 is 1.
            # Let's construct Z2 as 1010... (Site 0=L-1? No, site 0 to 25)
            # "1010...10"
            # Site 0 is 1, Site 1 is 0...
            if L % 2 == 0:
                # Ends in 0.
                s_z2 |= 1 << i
            else:
                pass # Not the case, L=26
    # Wait, s_z2 construction:
    # 26 bits.
    # i=0 (val 1): 1
    # i=1 (val 2): 0
    # i=2 (val 4): 1
    # ...
    s_z2 = sum(1 << i for i in range(0, L, 2))
    
    z2_idx = state_to_idx[s_z2]
    
    return vectors, basis, z2_idx

