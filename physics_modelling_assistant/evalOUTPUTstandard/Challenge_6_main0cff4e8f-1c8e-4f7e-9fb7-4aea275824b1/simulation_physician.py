def get_k_mesh(L):
    """
    Generate k-mesh grid points.
    Coordinates in reciprocal lattice basis (b1, b2).
    Returns list of k-vectors.
    """
    ks = []
    for l1 in range(L):
        for l2 in range(L):
            k = ((l1 / L) - 0.5) * b1 + ((l2 / L) - 0.5) * b2
            ks.append(k)
    return np.array(ks)

def compute_bands_and_eigvecs(ks):
    """
    Diagonalize Hamiltonian for all k points.
    Returns:
        energies: (L*L, dim) array
        eigvecs: (L*L, dim) array of eigenvectors (columns)
    """
    N_k = len(ks)
    energies = np.zeros((N_k, dim))
    eigvecs = np.zeros((N_k, dim), dtype=complex)
    
    print("Diagonalizing Hamiltonian...")
    for i, k in enumerate(ks):
        H = construct_hamiltonian(k)
        vals, vecs = eigh(H) # Ascending order
        energies[i, :] = vals
        eigvecs[i, :] = vecs.T # Store eigenvectors row-wise? 
        # eigh returns vecs[:, i] as i-th eigenvector.
        # We want energy[i, band] and vec[i, band] = state.
        # Let's keep vecs as (dim, dim) transposed to (dim, dim) effectively.
        # eigvecs[i] = vecs.T has shape (dim,)
        # If we store vecs.T, then eigvecs[i, j] is component j of state.
        # No, vecs[:, :] is [x_1, x_2...].
        # Let's reshape eigvecs later if needed.
        # Storing (N_k, dim) where second index is band index.
        eigvecs[i, :] = vecs.T 
    
    return energies, eigvecs

def calculate_chern_numbers(energies, eigvecs, N_bands):
    """
    Calculate Chern numbers for top N_bands bands using Fukui-Hatsugai method.
    """
    N_k = energies.shape[0]
    L_grid = int(np.sqrt(N_k))
    
    # Reshape to grid
    e_grid = energies.reshape((L_grid, L_grid, dim))
    v_grid = eigvecs.reshape((L_grid, L_grid, dim))
    
    # We need overlap between neighbors.
    # U_mu(k) = <u_k | u_{k+mu}> / | <...> |
    
    Chern_nums = np.zeros(N_bands)
    
    # Work with the target bands (top ones)
    # Indices: last N_bands bands
    band_indices = list(range(dim - N_bands, dim))
    
    for b_idx in band_indices:
        # Calculate link variables
        U1 = np.zeros((L_grid, L_grid), dtype=complex)
        U2 = np.zeros((L_grid, L_grid), dtype=complex)
        
        for n1 in range(L_grid):
            for n2 in range(L_grid):
                # k-point
                v_k = v_grid[n1, n2, :]
                
                # k + b1 (shift n1) -> index n1+1, n2
                n1_next = (n1 + 1) % L_grid
                v_k1 = v_grid[n1_next, n2, :]
                overlap1 = np.vdot(v_k, v_k1)
                U1[n1, n2] = overlap1 / np.abs(overlap1)
                
                # k + b2 (shift n2) -> index n1, n2+1
                n2_next = (n2 + 1) % L_grid
                v_k2 = v_grid[n1, n2_next, :]
                overlap2 = np.vdot(v_k, v_k2)
                U2[n1, n2] = overlap2 / np.abs(overlap2)
        
        # Field strength F12
        F_ij = np.zeros((L_grid, L_grid), dtype=complex)
        for n1 in range(L_grid):
            for n2 in range(L_grid):
                n1_next = (n1 + 1) % L_grid
                n2_next = (n2 + 1) % L_grid
                
                # U1(k) * U2(k+b1) * U1(k+b2)^* * U2(k)^*
                val = (U1[n1, n2] * 
                       U2[n1_next, n2] * 
                       np.conj(U1[n1, n2_next]) * 
                       np.conj(U2[n1, n2]))
                
                F_ij[n1, n2] = np.log(val)
        
        # Sum imaginary parts
        # Map log to (-pi, pi]
        ImF = np.imag(F_ij)
        # Adjust wrapping? np.log handles branch cut on negative real axis.
        # We need to ensure continuity in (-pi, pi].
        # Standard formula: sum(F) / 2pi i
        F_sum = np.sum(ImF)
        
        C = F_sum / (2 * np.pi)
        Chern_nums[b_idx - (dim - N_bands)] = C
        
    return Chern_nums

