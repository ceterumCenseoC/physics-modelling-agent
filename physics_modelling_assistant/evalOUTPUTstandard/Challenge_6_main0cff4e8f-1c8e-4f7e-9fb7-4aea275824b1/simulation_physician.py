def get_basis_vectors(layer):
    """
    Generate basis vectors Q for a given layer.
    For top (t): Q - q1 is a reciprocal lattice vector.
    For bottom (b): Q + q1 is a reciprocal lattice vector.
    Condition: |Q| < cutoff_radius.
    """
    # We need to find all G in the reciprocal lattice generated by g1, g2 
    # such that resulting Q satisfies conditions.
    # Since Q must be small (< 4.1|b1|), we can just scan integer pairs (n1, n2) 
    # such that |n1 b1 + n2 b2| < cutoff_radius * 2 (approx).
    
    basis = []
    
    # Scan range for integer combinations of reciprocal lattice vectors (which are g1, g2)
    # Actually, the reciprocal lattice of the Moire pattern is spanned by g1, g2.
    # But b1=g1, b2=g1+g2. They span the same lattice.
    
    limit = 5 # Should be enough for cutoff ~ 4 unit cells
    for n1 in range(-limit, limit + 1):
        for n2 in range(-limit, limit + 1):
            # Reciprocal lattice vector G
            G = n1 * b1 + n2 * b2 # Note: b2 is combination of g's, b1 is g1.
            # If we use g1, g2 directly:
            G_alt = n1 * g1 + n2 * g_vecs[1]
            
            if layer == 't':
                # Condition: Q - q1 = G  => Q = G + q1
                Q = G_alt + q1
            else: # 'b'
                # Condition: Q + q1 = G  => Q = G - q1
                Q = G_alt - q1
            
            if np.linalg.norm(Q) < cutoff_radius:
                basis.append(Q)
                
    # Deduplicate
    unique_basis = []
    seen = set()
    for q in basis:
        t = (round(q[0], 6), round(q[1], 6))
        if t not in seen:
            seen.add(t)
            unique_basis.append(q)
            
    return np.array(unique_basis)

