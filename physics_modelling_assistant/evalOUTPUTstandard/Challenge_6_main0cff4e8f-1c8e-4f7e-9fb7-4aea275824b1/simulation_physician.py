def construct_hamiltonian(k_vec):
    """
    Construct Hamiltonian matrix at momentum k.
    """
    H = np.zeros((dim, dim), dtype=complex)
    
    # Diagonal blocks: Kinetic + Potential
    # Top layer
    for i, Q in enumerate(Q_basis_t):
        # Kinetic
        k_minus_Q = k_vec - Q
        H[i, i] = (kinetic_const_meV_A2 / m_star_ratio) * np.dot(k_minus_Q, k_minus_Q)
        
        # Potential 2V sum cos(g.r +/- psi)
        # Matrix elements couple Q to Q +/- g_i
        # Top layer: +psi
        # Term V * sum (e^{i(g.r + psi)} + e^{-i(g.r + psi)})
        # In momentum space: V * sum (e^{i psi} delta(Q', Q-g) + e^{-i psi} delta(Q', Q+g))
        for g in g_vecs:
            # Check for Q' = Q + g
            Q_plus = Q + g
            # Find index of Q_plus in basis
            # Naive search is slow, but dim is small (~300)
            for j, Q_target in enumerate(Q_basis_t):
                if np.allclose(Q_plus, Q_target):
                    H[j, i] += V * np.exp(-1j * psi) # e^{i(g.r+psi)} shifts +g, coeff V e^{-i psi}? 
                    # Let's check signs carefully.
                    # Integral psi(r)* r.r' = sum V ... delta(k', k+g)
                    # H_{k', k} = V e^{i psi}
                    # Here k corresponds to basis vector Q. 
                    # H is H_{Q'}
                    # Potential V cos(g.r + psi) -> V/2(e^{i(g.r+psi)} + h.c.)
                    # Fourier transform of e^{i g.r} shifts k -> k+g.
                    # So <Q'|H|Q> gets V e^{i psi} if Q' = Q - g ??
                    # Let's write real space integral:
                    # int e^{i(k-Q)r} H e^{-i(k-Q')r} ~ H_{Q'-Q}
                    #谱projector.
                    # Term V e^{i(g.r + psi)} = V e^{i psi} e^{i g.r}
                    # Integral of e^{i g.r} connects diff components.
                    # If H has e^{i g.r}, then it couples k to k-g? No.
                    # Real op T(r). Matrix element <r'|T|r>.
                    # Formalism used in Wu PRL 2019:
                    # H_0 = hbar^2 k^2/2m + sum V_g e^{i g.r}
                    # Diagonalization in basis |k-Q>.
                    # <k-Q'| e^{i g.r} |k-Q> ~ delta(Q', Q-g).
                    # So if Hamiltonian has term coefficient A * e^{i g.r}, it connects Q to Q-g.
                    # Top layer potential: V(e^{i(g.r+psi)} + e^{-i(g.r+psi)})
                    # 1. e^{i(g.r+psi)}: connects Q to Q-g (since Q' = Q - g).
                    # 2. e^{-i(g.r+psi)}: connects Q to Q+g.
                    
                    # Let's look at Q_plus = Q + g. This matches term 2 (e^{-i...}).
                    # Coeff for e^{-i(g.r+psi)} is V * e^{-i psi}.
                    H[j, i] += V * np.exp(-1j * psi)
                    
            Q_minus = Q - g
            for j, Q_target in enumerate(Q_basis_t):
                if np.allclose(Q_minus, Q_target):
                    # Matches term 1 (e^{i(g.r+psi)}). Coeff V * e^{i psi}.
                    H[j, i] += V * np.exp(1j * psi)

    # Bottom layer
    offset = Nt
    for idx_b, Q in enumerate(Q_basis_b):
        row = offset + idx_b
        # Kinetic
        k_minus_Q = k_vec - Q
        H[row, row] = (kinetic_const_meV_A2 / m_star_ratio) * np.dot(k_minus_Q, k_minus_Q)
        
        # Potential: -psi
        # V (e^{i(g.r - psi)} + e^{-i(g.r - psi)})
        for g in g_vecs:
            Q_plus = Q + g # From e^{-i(g.r - psi)}
            for j, Q_target in enumerate(Q_basis_b):
                if np.allclose(Q_plus, Q_target):
                    H[offset + j, row] += V * np.exp(1j * psi) # coeff V e^{i(-psi)} = V e^{-i psi}
                                                              # Wait. e^{-i(g.r-psi)} = e^{i psi} e^{-i g.r}
                                                              # Connects Q to Q+g. Coeff V e^{i psi}. Correct.
                    
            Q_minus = Q - g # From e^{i(g.r - psi)}
            for j, Q_target in enumerate(Q_basis_b):
                if np.allclose(Q_minus, Q_target):
                    H[offset + j, row] += V * np.exp(-1j * psi) # coeff V e^{-i(-psi)} = V e^{i psi}?
                                                               # e^{i(g.r-psi)} = e^{-i psi} e^{i g.r}
                                                               # Connects Q to Q-g. Coeff V e^{-i psi}. Correct.

    # Off-diagonal blocks: Tunneling
    # w sum e^{-i q.r} (t to b)
    # w sum e^{i q.r} (b to t)
    
    # Top to Bottom <Q_t| H |Q_b> = w * sum delta(Q_t - q - Q_b, G)
    # Or Wu notation: T(r) = w sum e^{i q_j.r}. 
    # Wu 2019 Eq 3: T(r) = w sum T_j(r)
    # Usually H = diag + T(r).
    # <r,t|H|r',b> = T(r-r').
    # Matrix element <k-Q_t, t | H | k-Q_b, b> ~ w sum delta(Q_t - Q_b - q)
    # Note: The Hamiltonian in problem statement has e^{-i q.r} in top-right.
    # This couples t(r) to b(r'). 
    # Basis functions are plane waves. 
    # <Q_t| e^{-i q.r} |Q_b> is nonzero if Q_t = Q_b - q (promoted -q).
    # Let's check: Int e^{i(k-Q_t)r} e^{-i q.r} e^{-i(k-Q_b)r} = delta(Q_t + q - Q_b)
    # So coupling exists if Q_b = Q_t + q.
    # Element = w.
    
    # Loop over q_i
    for q in q_vecs:
        # Top row, Bottom col
        # For each Q_t, find Q_b = Q_t + q
        for i_t, Q_t in enumerate(Q_basis_t):
            Q_b_target = Q_t + q
            for j_b, Q_b in enumerate(Q_basis_b):
                if np.allclose(Q_b, Q_b_target):
                    H[offset + j_b, i_t] += w # Top row: i_t, Bottom col: offset+j_b
                    # Wait, matrix form is 
                    # ( H_tt   H_tb )
                    # ( H_bt   H_bb )
                    # Row is bra <t|, Col is ket |b>.
                    # So H[i_t, offset + j_b] is correct for <t|H|b>.
                    # Problem statement: Top right element is w sum e^{-i q.r}.
                    H[i_t, offset + j_b] += w 
                    
        # Bottom row, Top col
        # Conjugate term w e^{i q.r}
        # <Q_b| e^{i q.r} |Q_t> nonzero if Q_b = Q_t - q.
        # Element = w*
        # Since w is real in our parameters (-18.8), w* = w.
        for i_b, Q_b in enumerate(Q_basis_b):
            Q_t_target = Q_b - q
            for j_t, Q_t in enumerate(Q_basis_t):
                if np.allclose(Q_t, Q_t_target):
                    H[i_b, offset + j_t] += w
                    # H[bb, bt] -> H[offset+i_b, j_t]
                    
    return H

