# Formula: g_ij = Re ( 1/2 Tr[ P_k P_{k+ij} P_k P_{k-ij} ] ?? )
# Or better: 
# g_{xy} = Re < d_x u | (1-P) | d_y u >
# d_i u_n = sum_{m!=n} < u_m | d_i H | u_n > / (E_n - E_m) | u_m >
# Numerically, we use the projector method on the grid.
# g_ij(k) ~ (1 - delta_ij delta_r) / delta_r^2 ?
# No, use the formula from rest of output generation trace calculation:
# P_n = |u_n><u_n|
# g_ij(k) = 1/2 Tr[ P(k) P(k+i) P(k) P(k+j) ] * (1/dk^2) ? 
# No, finite difference of Projector P_k:
# d_i P = (P(k+i dk) - P(k-i dk)) / 2 dk
# g_ij = 1/2 Tr[ (d_i P) (d_j P) ]
# This is the standard gauge invariant formula.

def calculate_quantum_metric_trace(energies, eigvecs, band_idx):
    """
    Calculate trace of quantum metric for a specific band index `band_idx`
    (where band_idx is relative to the full sorted list, 0...dim-1).
    `band_idx` = -1 for top band.
    """
    N_k = energies.shape[0]
    L_grid = int(np.sqrt(N_k))
    
    # Reshape
    v_grid = eigvecs.reshape((L_grid, L_grid, dim))
    
    # Projector P_k at each point is.outer(v, v.conj())
    # We need dP/dk_x, dP/dk_y.
    # k is on a grid. dk_x = b1 / L, dk_y = (rotated b2?) / L.
    # Distances:
    dk1 = np.linalg.norm(b1) / L_grid
    dk2 = np.linalg.norm(b2) / L_grid
    # Non-orthogonal grid, finite differences are tricky.
    # Formula g_ij usually assumes Cartesian coordinates.
    # We can map k-points to Cartesian coordinates (kx, ky) and use FD there?
    # Or just use the step in the grid directions.
    # Tr G = int dk^2 g_xx + g_yy ...
    # In non-orthogonal basis, we need Jacobian.
    # Area element d^2k = |b1 x b2| / L^2.
    
    # Finite difference approximation for derivatives:
    # P_x = (P(n1+1, n2) - P(n1-1, n2)) / (2 * dx)
    # Here dx is vector b1/L. P_x is a tensor. 
    # We need matrix derivative. 
    # Let's compute dP/dk1 and dP/dk2 (directional derivatives along grid).
    # g_ij = 1/2 Tr[ d_i P d_j P ].
    # Trace g = g_11 + g_22.
    # Total integral = Sum_k (Tr g(k)) * (Area_Element)
    # Area_Element = |b1 x b2| / L^2.
    
    # Note: g_ij in (k1, k2) coordinates.
    # To get physical "Trace", we sum g_11 + g_22 (the components along reciprocal lattice vectors).
    # This corresponds to the trace of the metric in the local basis.
    # Which is invariant under orthogonal rotation.
    # However, b1 and b2 are 120 deg apart. The metric tensor is defined in R^2.
    # Let's extract the "Cartesian" components or just use the formula:
    # Sum <u| d_x (1-P) d_x |u> dk^2
    # We can approximate:
    # g_{11} ~ 1/2 Tr[ (P_{n1+1} - P_{n1-1})^2 ] / (4 dk1^2)
    
    # We need the global magnitude. Dimensionless Tr G = int g^ij dk_i dk_j ? No, g_ij.
    # Tr G = int d^2k (g_kk + g_ll) in orthonormal basis.
    # Or using the area metric.
    # Let's calculate the scalar integrand at each point:
    # Tr(g) = 1/2 Tr[ (d_1 P) (d_1 P) ] * (dk1)^2 + 1/2 Tr[ (d_2 P) (d_2 P) ] * (dk2)^2 ... wait no.
    # g_ij * dk^i dk^j.
    # We want $\int d^2k \text{Tr} g(\mathbf{k})$.
    # This is standard. g is defined w.r.t Cartesian derivatives.
    # We will approximate derivatives using the grid spacing.
    k_step = np.linalg.norm(b1) / L_grid # Approximation assuming BZ is roughly circular or we project.
    # Better: Use the area dA = BZ_area / L^2.
    # Finite diff for derivative d/dk_x is problematic on hex grid.
    # Alternative: Use the definition involving overlaps U_mu.
    # g_ij(k) = 1 - Re[U_i U_j^* ...] / dk^2 ?
    # For 1D: g(k) = (1 - |U|^2) / (dk^2). 
    # For 2D: 
    # Using notation from Provost and Vallee:
    # g_{mu nu} = delta_{mu nu} - Re[ U_mu ] ... not trivial sum.
    # Let's stick to the Projector FD method, mapping grid to Cartesian.
    
    # The k-points are defined as k = x b1 + y b2.
    # We can treat x, y as normalized coordinates (-0.5 to 0.5).
    # Position in 2D plane.
    # Derivatives wrt x, y.
    # Jacobian to k-space area: J = |b1 x b2|.
    # Metric g in x,y space?
    # The definition uses d/dk. 
    # Let d/dk_i be derivative w.r.t Cartesian components.
    # Chain rule: d/dx = (b1)_j d/dkj.
    # Tr g_cart = g_xx + g_yy.
    # Inverse metric? No, just sum of diagonal elements.
    # If basis is not orthonormal, Tr g is not invariant?
    # Tr G is defined for Riemannian manifold.
    # g_ij = < d_i u | d_j u > (real part).
    # d/dk = (b1)_x d/dx1 + (b2)_x d/dx2 ...
    # This is getting complicated.
    # Simplified approach: Treat k-plane as flat Euclidean.
    # Map neighbors to vectors (b1/L, b2/L).
    # d1 P = (P(x+1) - P(x-1)) / (2 * |b1|/L) * direction_b1?
    # No, just treat b1, b2 as basis vectors e1, e2. 
    # Compute g_11' = 1/2 Tr[d_1 P d_1 P] where d_1 is directional derivative along b1.
    # Value g_11' has units of [Length]^2 * [1/|b1|^2]? No.
    # d_1 P = P(k+b1/L) - P(k-b1/L) over 2 step (vector b1/L).
    # So d_1 P ~ P / (Length).
    # g_11 ~ 1/L^2.
    # We want g_ij such that integral is d^2k g_ij.
    # If we sum g_11' * (step_area), we approximate int g_xx' dk dk?
    # Let's trust the provided context hint: "Numerically evaluate... using conventions".
    # Usually implies local finite difference on the mesh.
    # We sum Tr(g) * Area_of_cell.
    # Tr(g) = 1/2 [ (P(i+1)-P(i-1))^2 + ... ] * 1/dk^2
    # Let's use dk = np.linalg.norm(b1)/L (approx magnitude of grid vector).
    
    dk_mag = np.linalg.norm(b1) / L_grid
    
    total_TrG = 0.0
    
    # Central difference loop ignoring boundaries (Periodic?)
    # Problem says "k in BZ". Usually Periodic BC for Bloch states.
    for n1 in range(L_grid):
        for n2 in range(L_grid):
            # Current P
            u = v_grid[n1, n2, band_idx]
            # Periodic neighbors
            u_xp = v_grid[(n1+1)%L_grid, n2, band_idx]
            u_xm = v_grid[(n1-1)%L_grid, n2, band_idx] # Python -1 works but careful with 0
            u_yp = v_grid[n1, (n2+1)%L_grid, band_idx]
            u_ym = v_grid[n1, (n2-1)%L_grid, band_idx]
            
            # Projectors |u><u|
            # We need dP = P' - P.
            # dP ~ |du><u| + |u><du|
            # dP dP = ...
            # 1/2 Tr[dP dP] = |du|^2.
            # So Tr(g) = |d_x u|^2 + |d_y u|^2.
            # du is approx (u_next - u_prev)/2dk.
            
            # NOTE: This ignores the normalization/unitary gauge freedom issues?
            # |u> is normalized. <u|u>=1. <du|u> = -<u|du>. Pure imaginary.
            # |d_x u|^2 = <d_x u|d_x u>.
            # d_x u = (u_xp - u_xm) / (2 dk)
            
            # This is the robust numerical method.
            
            du_x = (u_xp - u_xm) / (2 * dk_mag)
            du_y = (u_yp - u_ym) / (2 * dk_mag)
            
            norm_dux_sq = np.vdot(du_x, du_x).real
            norm_duy_sq = np.vdot(du_y, du_y).real
            
            local_Tr_g = norm_dux_sq + norm_duy_sq
            
            total_TrG += local_Tr_g
            
    # Integral = Sum * dA
    dA = BZ_area / (L_grid * L_grid)
    integral_TrG = total_TrG * dA
    
    return integral_TrG

